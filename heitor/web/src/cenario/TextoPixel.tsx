const SEM_ACENTO: Record<string, string> = { Á: "A", Ã: "A", Â: "A", É: "E", Ê: "E", Í: "I", Ó: "O", Õ: "O", Ô: "O", Ú: "U", Ç: "C" };

export function larguraTexto(texto: string): number {
  return Math.max(0, texto.length * 4 - 1);
}

export function TextoPixel({ texto, x, y, cor }: { texto: string; x: number; y: number; cor: string }) {
  const letras = texto
    .toUpperCase()
    .split("")
    .map((c) => SEM_ACENTO[c] ?? c);
  const largura = larguraTexto(texto);
  const caminho = letras
    .map((c, i) =>
      (GLIFOS[c] ?? GLIFOS[" "] ?? [])
        .map((linha, ly) =>
          linha
            .split("")
            .map((px, lx) => (px === "#" ? `M${i * 4 + lx} ${ly}h1v1h-1z` : ""))
            .join(""),
        )
        .join(""),
    )
    .join("");
  return (
    <svg
      aria-hidden
      viewBox={`0 0 ${largura} 5`}
      width={largura}
      height={5}
      shapeRendering="crispEdges"
      style={{ position: "absolute", left: x, top: y, zIndex: 6 }}
    >
      <path d={caminho} fill={cor} />
    </svg>
  );
}
